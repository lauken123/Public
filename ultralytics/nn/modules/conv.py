# 創新點二：NoiseFilteredFusion (借鑒 Mobile U-ViT 的噪聲過濾融合模組)
# 物理機制：替代傳統的 Concat 算子。
# 傳統 Concat 會將 Backbone 帶有強烈網格線的淺層特徵直接注入 Head，污染深層语义。
# 本模組在拼接前，先對淺層特徵進行統計量分析，生成二維空間掩碼，主動剔除幾何偽影。
# =====================================================================

class NoiseFilteredFusion(nn.Module):
    """
    噪聲過濾跨層特徵融合模組，接管 [shallow_feature, deep_feature] 的融合
    """
    def __init__(self):
        super().__init__()
        # 用於動態捕捉並抑制規律性網格噪聲的非對稱空間濾波器
        self.spatial_filter = nn.Sequential(
            nn.Conv2d(2, 1, kernel_size=7, padding=3, bias=False),
            nn.Sigmoid()
        )

    def forward(self, x):
        # x 是一個列表：[shallow, deep]
        # shallow: 來自主幹的淺層高分辨率特徵（網格噪聲極大）
        # deep: 來自深層網絡上采樣過來的語義特徵（乾淨但邊緣模糊）
        shallow, deep = x[0], x[1]
        
        # 提取淺層特徵的空間特徵分佈
        avg_out = torch.mean(shallow, dim=1, keepdim=True)
        max_out, _ = torch.max(shallow, dim=1, keepdim=True)
        spatial_map = torch.cat([avg_out, max_out], dim=1)
        
        # 生成噪聲過濾掩碼
        mask = self.spatial_filter(spatial_map)
        
        # 清洗淺層特徵後，再與深層特徵進行 Concat 拼接
        shallow_filtered = shallow * mask
        return torch.cat([shallow_filtered, deep], dim=1)
        
