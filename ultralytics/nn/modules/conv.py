# 創新點一：DWTDownsample (基於離散小波變換的頻域解耦下采樣模組)
# 物理機制：將特徵圖解耦為低頻(LL)與高頻(LH, HL, HH)子帶。
# 規律的幾何網格線會集中在 LH 和 HL 子帶，而蟲體突變信號集中在 HH 子帶。
# 通過頻域閘控自適應壓低網格子帶，放大蟲體子帶，從源頭清洗噪聲。
# =====================================================================

class DWTDownsample(nn.Module):
    """
    頻域解耦下采樣，替代傳統的步長卷積或池化
    """
    def __init__(self, c1, c2):
        super().__init__()
        self.c1 = c1
        self.c2 = c2
        
        # 構造 Haar 小波的 4 個基本基函數：LL(均值), LH(水平), HL(垂直), HH(對角線)
        # shape: (4, 1, 2, 2)
        kernel = torch.tensor([
            [[[1.0,  1.0], [ 1.0,  1.0]]],  # LL 低頻近似
            [[[1.0, -1.0], [ 1.0, -1.0]]],  # LH 水平高頻（捕捉垂直網格線）
            [[[1.0,  1.0], [-1.0, -1.0]]],  # HL 垂直高頻（捕捉水平網格線）
            [[[1.0, -1.0], [-1.0,  1.0]]]   # HH 對角線高頻（捕捉孤立微小蟲體）
        ], dtype=torch.float32) / 2.0
        
        # 為輸入的每個通道複製一組小波核，用於深度可分離卷積 (Groups = c1)
        # 輸出通道數將會自動變為 4 * c1
        self.register_buffer('weight', kernel.repeat(c1, 1, 1, 1))
        
        # 頻域注意力閘控 (Frequency-domain Gate)
        self.gate = nn.Sequential(
            nn.AdaptiveAvgPool2d(1),
            nn.Conv2d(4 * c1, c1, 1, bias=False),
            nn.ReLU(inplace=True),
            nn.Conv2d(c1, 4 * c1, 1, bias=False),
            nn.Sigmoid()
        )
        
        # 通道投影與標準化，將 4 * c1 映射到用戶指定的 c2
        self.proj = nn.Conv2d(4 * c1, c2, 1, 1, 0, groups=4, bias=False)
        self.bn = nn.BatchNorm2d(c2)
        self.act = nn.SiLU(inplace=True)

    def forward(self, x):
        b, c, h, w = x.shape
        # 確保輸入分辨率為偶數，避免小波變換邊界對不齊
        if h % 2 != 0 or w % 2 != 0:
            x = nn.functional.pad(x, (0, w % 2, 0, h % 2))
            
        # 執行小波分解：利用群卷積加速，空間分辨率減半，通道數變為 4 倍
        dwt_out = nn.functional.conv2d(x, self.weight, stride=2, padding=0, groups=c)
        
        # 頻域閘控：動態計算哪些頻率子帶含有噪聲並給予抑制
        attention = self.gate(dwt_out)
        dwt_filtered = dwt_out * attention
        
        # 投影回常規特徵空間
        return self.act(self.bn(self.proj(dwt_filtered)))


